// Package gen generates the JSON Schema files of an NTF service from its Go
// types, by the rules every service follows: a request refuses properties it
// does not declare and a response allows them, every type is inlined rather
// than put in $defs, and only the root is given the $id, the title and the
// const of its type property. A schema from a Mapper goes in as it is, with any
// of those it holds itself.
//
// Only tests may import this package. Schemas are generated by a test and
// committed, then embedded and served, so nothing needs to reflect at runtime.
// Keeping the reflector here, away from the packages that hold the types, is
// what keeps invopop/jsonschema out of every binary.
//
// It knows nothing of any one service. The caller gives the type id, the $id
// and any Mapper, and keeps its JSONSchema and JSONSchemaExtend hooks in its
// own _test.go files, so that the package holding the types can use this one
// from an in-package test.
package gen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"reflect"

	invopop "github.com/invopop/jsonschema"
)

// Mapper gives the schema of a Go type that cannot carry a JSONSchema hook,
// such as one of another package, and nil for any other type. A nil Mapper
// maps nothing. The reflector sets Schema.Description on a struct field from
// the field's tags, over any the Mapper gave, so a Mapper puts a description in
// Extras. That field must then have no description tag, since the encoded
// schema would hold the key twice.
type Mapper func(reflect.Type) *invopop.Schema

// Request returns the encoded schema of request type t, whose type id is typ
// and whose $id is url. It refuses properties t does not declare.
func Request(t reflect.Type, typ, url string, mapper Mapper) ([]byte, error) {
	return reflectSchema(t, typ, url, mapper, false)
}

// Response returns the encoded schema of response type t, whose type id is typ
// and whose $id is url. It allows properties t does not declare.
func Response(t reflect.Type, typ, url string, mapper Mapper) ([]byte, error) {
	return reflectSchema(t, typ, url, mapper, true)
}

// Encode returns s as indented JSON, as the committed files hold it.
func Encode(s *invopop.Schema) ([]byte, error) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	err := enc.Encode(s)
	if err != nil {
		return nil, err
	}

	return buf.Bytes(), nil
}

// reflectSchema returns the encoded schema of t. Only the root gets the $id,
// the title and the const of its type property, since a nested type may have
// a type of its own.
func reflectSchema(t reflect.Type, typ, url string, mapper Mapper, additional bool) ([]byte, error) {
	r := &invopop.Reflector{
		Anonymous:                  true,
		AllowAdditionalProperties:  additional,
		RequiredFromJSONSchemaTags: true,
		DoNotReference:             true,
		Mapper:                     mapper,
	}
	s := r.ReflectFromType(t)

	s.ID = invopop.ID(url)
	s.Title = typ

	if s.Properties == nil {
		return nil, fmt.Errorf("%w: %s", ErrNoTypeProperty, t)
	}
	prop, ok := s.Properties.Get("type")
	if !ok {
		return nil, fmt.Errorf("%w: %s", ErrNoTypeProperty, t)
	}
	prop.Const = typ

	return Encode(s)
}
